    wanted = referenced(db)
    # Plus the one this server already replays every tick, so the decoder has a
    # sample it can be checked against.
    wanted.add("a0001_tutorial_heal_on_low_health")

    rows = [
        row
        for row in db.execute(
            f"SELECT rowid - 1, {', '.join(FIELDS)} FROM _Template_StatusEffect"
            " ORDER BY rowid"
        )
        if row[1] in wanted
    ]

    def num(v, d=0.0):
        return d if v is None else round(float(v), 4)

    def whole(v, d=0):
        return d if v is None else int(v)

    def text(v):
        return "" if v is None else str(v)

