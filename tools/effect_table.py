#: How an effect entry in a skill's list is written: the effect id, then keyed
#: fields, then the numbered parameters the modifiers substitute.
#:
#:   C   chance. 1.0 is unconditional; 0.0 marks the entries that need an item or a
#:       talent the character does not have, which is most of them.
#:   D   duration in seconds, DP the duration in player-versus-player.
#:   TR  a flag whose meaning is not established.
#:   ON  the trigger: Immediate, HitCritical, SkillStart, kill, LOWHEALTH.
#:   $n  the parameters, substituted into the modifiers' $0, $1, $2.
ENTRY_KEYS = ("C", "D", "DP", "TR", "DE", "OZ", "ON")


@dataclass(frozen=True)
class Modifier:
    """One change an effect makes: ``Speed:$0,relative,Movement``."""

    #: What is changed: Speed, Damage, Resistance, SkillDamage, ResourceCost,
    #: LifeLeech, ActorStatusEffect, StopStatusEffect.
    attribute: str
    #: The parameter reference, ``$0``, or a literal value.
    value: str
    #: ``relative`` (a fraction of the base) or ``absolute``.
    mode: str
    #: What it applies to: a damage type, a skill id, Movement, Min and Max.
    targets: tuple[str, ...]

    def amount(self, parameters: dict[str, float]) -> float | None:
        """The modifier's value with *parameters* substituted, or None if unknown."""
        if self.value.startswith("$"):
            return parameters.get(self.value)
        try:
            return float(self.value)
        except ValueError:
            return None


def parse_modifiers(packed: str) -> tuple[Modifier, ...]:
    """Read a StartModifiers / TickModifiers / StopModifiers string."""
    out = []
    for clause in packed.split(";"):
        clause = clause.strip()
        if not clause or ":" not in clause:
            continue
        attribute, _, rest = clause.partition(":")
        parts = [p.strip() for p in rest.split(",") if p.strip()]
        if not parts:
            continue
        value = parts[0]
        mode = parts[1] if len(parts) > 1 else ""
        targets = tuple(parts[2:]) if len(parts) > 2 else ()
        if mode not in ("relative", "absolute"):
            # Not a value-and-mode clause -- ActorStatusEffect:addAE,other_effect,...
            # keeps its whole tail as targets so nothing is silently dropped.
            targets = tuple(parts[1:])
            mode = ""
        out.append(Modifier(attribute.strip(), value, mode, targets))
    return tuple(out)


@dataclass(frozen=True)
class Entry:
    """One effect as a skill names it, with the parameters that skill supplies."""

    effect: str
    chance: float
    duration: float
    duration_pvp: float
    trigger: str
    parameters: tuple[tuple[str, float], ...]

    @property
    def certain(self) -> bool:
        """Whether the effect applies unconditionally.

        A chance of 0.0 does not mean "never" -- it marks the entries that need an
        item, a talent or a set bonus the character does not have. Most of a skill's
        list is those, which is why warshout names sixteen effects and grants three.
        """
        return self.chance >= 1.0

    @property
    def substitutions(self) -> dict[str, float]:
        return dict(self.parameters)


def parse_entries(packed: str) -> tuple[Entry, ...]:
    """Read a skill's VictimStatusEffects / UserStatusEffects / Location list."""
    out = []
    for clause in (packed or "").split(";"):
        clause = clause.strip()
        if not clause:
            continue
        parts = [p.strip() for p in clause.split(",") if p.strip()]
        if not parts:
            continue
        keyed: dict[str, str] = {{}}
        params: list[tuple[str, float]] = []
        for part in parts[1:]:
            key, _, value = part.partition(":")
            key = key.strip()
            if key.startswith("$"):
                try:
                    params.append((key, float(value)))
                except ValueError:
                    pass
            else:
                keyed[key.upper()] = value.strip()

        def number(key, default=0.0):
            try:
                return float(keyed.get(key, default))
            except ValueError:
                return default

        out.append(
            Entry(
                effect=parts[0],
                chance=number("C"),
                duration=number("D"),
                duration_pvp=number("DP"),
                trigger=keyed.get("ON", ""),
                parameters=tuple(params),
            )
        )
    return tuple(out)


@dataclass(frozen=True)
class Effect:
    """One row of the client's status effect table."""

    #: The wire index: the row before its row, the same convention as a skill's.
    #: Confirmed by decoding the 0x004F this server already replays, whose single
    #: effect reads 1350 and is row 1351, ``a0001_tutorial_heal_on_low_health`` --
    #: which is exactly what a tutorial dungeon would carry.
    wire: int
    id: str
    duration: float
    tick_rate: float
    max_stack: int
    start_modifiers: str
    tick_modifiers: str
    stop_modifiers: str
    done_modifiers: str
    exclusive_group: str
    groups: str

    @cached_property
    def starts(self) -> tuple[Modifier, ...]:
        return parse_modifiers(self.start_modifiers)

    @cached_property
    def ticks(self) -> tuple[Modifier, ...]:
        return parse_modifiers(self.tick_modifiers)

    @property
    def changes_anything(self) -> bool:
        return bool(self.starts or self.ticks)


