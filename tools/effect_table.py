from dataclasses import dataclass
from functools import cached_property


#: How an effect entry in a skill's list is written: the effect id, then keyed
#: fields, then the numbered parameters the modifiers substitute.
#:
#:   C   chance. 1.0 is unconditional; 0.0 marks the entries that need an item or a
#:       talent the character does not have, which is most of them.
#:   D   duration in seconds, DP the duration in player-versus-player.
#:   TR  a flag whose meaning is not established.
#:   ON  the trigger: Immediate, HitCritical, SkillStart, kill, LOWHEALTH.
#:   $n  the parameters, substituted into the modifiers' $0, $1, $2.
ENTRY_KEYS = ("C", "D", "DP", "TR", "DE", "OZ", "ON")


@dataclass(frozen=True)
class Modifier:
    """One change an effect makes: ``Speed:$0,relative,Movement``."""

    #: What is changed: Speed, Damage, Resistance, SkillDamage, ResourceCost,
    #: LifeLeech, ActorStatusEffect, StopStatusEffect.
    attribute: str
    #: The parameter reference, ``$0``, or a literal value.
    value: str
    #: ``relative`` (a fraction of the base) or ``absolute``.
    mode: str
    #: What it applies to: a damage type, a skill id, Movement, Min and Max.
    targets: tuple[str, ...]

    @property
    def skills_named(self) -> tuple[str, ...]:
        """The skill ids this modifier names, if it names any.

        A target can carry a suffix -- ``angrystrike#skillDamageRel`` -- which is
        stripped, because the part before the hash is the template id.
        """
        if self.attribute not in SKILL_ATTRIBUTES:
            return ()
        return tuple(target.split("#")[0] for target in self.targets)

    def amount(self, parameters: dict[str, float]) -> float | None:
        """The modifier's value with *parameters* substituted, or None if unknown."""
        if self.value.startswith("$"):
            return parameters.get(self.value)
        try:
            return float(self.value)
        except ValueError:
            return None


#: Modifier attributes that reach into a *skill's* definition, or spawn an actor.
#: Serving one asks the client to resolve something the character does not own, and it
#: asserts rather than shrug: ``skillTemplateId.IsValid()`` in
#: Game::ActorStatusEffectModule, reached through GetSkillLocaAddModifications.
#:
#: The two that produced it are identifiable:
#:
#:   set_cny2026_warrior_earthquake_dmg
#:       SkillStatusEffect:modLE,earthquake,skill_earthquake_aura,$1:-0.05
#:   warrior_talent_damage_dealer_cooldown_reduction
#:       ActiveCoolDown:$talent_warrior_dd_cd,absolute,Skill01..Skill20
#:
#: One rewrites another skill's status effects, the other names skill *slots*. Both go
#: through the skill-template path, and neither belongs on a character with no set and
#: no talents.
FORBIDDEN_ATTRIBUTES = frozenset({
    "SkillStatusEffect", "ActiveCoolDown", "Localize", "SkillSequence",
    "UnlockHiddenSkills", "SkinModifier", "Minion", "Pet", "Mounted",
    "DropAmount",
    # A capture-the-flag flag, from warshout's ctfdropflag. Not in the tooltip, and
    # nothing to do with a dungeon.
    "PVPEventModifier",
})

#: Modifier attributes that name a skill. Safe only when every skill they name is one
#: the character actually has -- which keeps warshout's angrystrike buff and
#: frenzyshout's life leech, both of which name warrior skills a level 100 warrior has.
SKILL_ATTRIBUTES = frozenset({
    "SkillDamage", "SkillHitDamage", "LifeLeech", "ResourceCost", "CoolDown",
    "SkillDamageType",
})

#: Effect ids this server will force when asked. A skill's own effects and the
#: crowd-control and damage-over-time debuffs, and nothing that depends on equipment,
#: a set or a talent -- because forcing those is both nonsense on a character who has
#: none and the road to the assertion above.
FORCEABLE_PREFIXES = ("skill_", "debuff_", "buff_")


def forceable(effect_id: str) -> bool:
    """Whether *effect_id* is one this server will force."""
    return effect_id.startswith(FORCEABLE_PREFIXES)


def parse_modifiers(packed: str) -> tuple[Modifier, ...]:
    """Read a StartModifiers / TickModifiers / StopModifiers string."""
    out = []
    for clause in packed.split(";"):
        clause = clause.strip()
        if not clause:
            continue
        if ":" not in clause:
            # A bare word is a flag with no value: skill_mighty360_debuff_taunt's
            # whole StartModifiers is "Taunt". Dropping those made the effect look
            # like it changed nothing, and the tool that checks tooltips against what
            # is served then blamed the wrong thing.
            out.append(Modifier(clause, "", "", ()))
            continue
        attribute, _, rest = clause.partition(":")
        parts = [p.strip() for p in rest.split(",") if p.strip()]
        if not parts:
            continue
        value = parts[0]
        mode = parts[1] if len(parts) > 1 else ""
        targets = tuple(parts[2:]) if len(parts) > 2 else ()
        if mode not in ("relative", "absolute"):
            # Not a value-and-mode clause -- ActorStatusEffect:addAE,other_effect,...
            # keeps its whole tail as targets so nothing is silently dropped.
            targets = tuple(parts[1:])
            mode = ""
        out.append(Modifier(attribute.strip(), value, mode, targets))
    return tuple(out)


@dataclass(frozen=True)
class Entry:
    """One effect as a skill names it, with the parameters that skill supplies."""

    effect: str
    chance: float
    duration: float
    duration_pvp: float
    trigger: str
    parameters: tuple[tuple[str, float], ...]

    @property
    def certain(self) -> bool:
        """Whether the effect applies unconditionally.

        A chance of 0.0 does not mean "never" -- it marks the entries that need an
        item, a talent or a set bonus the character does not have. Most of a skill's
        list is those, which is why warshout names sixteen effects and grants three.
        """
        return self.chance >= 1.0

    @property
    def substitutions(self) -> dict[str, float]:
        return dict(self.parameters)


def parse_entries(packed: str) -> tuple[Entry, ...]:
    """Read a skill's VictimStatusEffects / UserStatusEffects / Location list."""
    out = []
    for clause in (packed or "").split(";"):
        clause = clause.strip()
        if not clause:
            continue
        parts = [p.strip() for p in clause.split(",") if p.strip()]
        if not parts:
            continue
        keyed: dict[str, str] = {{}}
        params: list[tuple[str, float]] = []
        for part in parts[1:]:
            key, _, value = part.partition(":")
            key = key.strip()
            if key.startswith("$"):
                try:
                    params.append((key, float(value)))
                except ValueError:
                    pass
            else:
                keyed[key.upper()] = value.strip()

        def number(key, default=0.0):
            try:
                return float(keyed.get(key, default))
            except ValueError:
                return default

        out.append(
            Entry(
                effect=parts[0],
                chance=number("C"),
                duration=number("D"),
                duration_pvp=number("DP"),
                trigger=keyed.get("ON", ""),
                parameters=tuple(params),
            )
        )
    return tuple(out)


@dataclass(frozen=True)
class Effect:
    """One row of the client's status effect table."""

    #: The wire index: the row before its row, the same convention as a skill's.
    #: Confirmed by decoding the 0x004F this server already replays, whose single
    #: effect reads 1350 and is row 1351, ``a0001_tutorial_heal_on_low_health`` --
    #: which is exactly what a tutorial dungeon would carry.
    wire: int
    id: str
    duration: float
    tick_rate: float
    max_stack: int
    start_modifiers: str
    tick_modifiers: str
    stop_modifiers: str
    done_modifiers: str
    exclusive_group: str
    groups: str
    #: The animation the client plays for this effect, and the reason the sequencer
    #: field matters: a0001_tutorial_heal_on_low_health has none, so the recording
    #: never exercised that path, and every effect worth sending does have one.
    start_sequence: str
    tick_sequence: str
    start_animation: str
    #: The effects this aura puts on whatever stands inside it, as the column holds
    #: them: a semicolon-separated list of effect ids. See :attr:`aura_effects`.
    aura_effect_ids: str = ""
    #: How wide the aura reaches, in world units. 2.15 for earthquake's own aura,
    #: 3.0 for its shockwave, 5.75 for Dragon Hide.
    aura_radius: float = 0.0
    #: Who it reaches: Creator, Enemies, Allies.
    aura_targets: str = ""

    @property
    def aura_effects(self) -> tuple[str, ...]:
        """The ids in :attr:`aura_effect_ids`, split.

        A single-value column that is sometimes a list is exactly the shape that gets
        read as one name and found missing: looking up the whole of
        ``"skill_earthquake_dmg;skill_earthquake_debuff_movementspeed"`` finds
        nothing, and nothing is what earthquake did.
        """
        return tuple(
            part.strip() for part in self.aura_effect_ids.split(";") if part.strip()
        )

    @cached_property
    def starts(self) -> tuple[Modifier, ...]:
        return parse_modifiers(self.start_modifiers)

    @cached_property
    def ticks(self) -> tuple[Modifier, ...]:
        return parse_modifiers(self.tick_modifiers)

    @property
    def changes_anything(self) -> bool:
        return bool(self.starts or self.ticks)

    @property
    def over_time(self) -> bool:
        """Whether the effect deals damage on a tick rather than at once.

        debuff_dot_poison, debuff_dot_burn and debuff_dot_bleeding all carry
        ``CurrHealthPointsDmg`` in TickModifiers. The client would do this itself given
        the effect, but every one of them is animated and an animated effect cannot be
        sent yet -- so the damage is served and the green bubbles are not.
        """
        return any(
            modifier.attribute == "CurrHealthPointsDmg" for modifier in self.ticks
        )

    @property
    def animated(self) -> bool:
        """Whether the client plays a sequence or an animation for this effect.

        The recorded element this server copies belongs to
        a0001_tutorial_heal_on_low_health, which has none of the three -- so replaying
        it never entered the sequencer, and the vectors in the element's tail were
        never used. An animated effect does enter it, with a tail copied from an effect
        that had no tracks and no position for them, and the client asserts:

            Util::FixedArray<Core::Ptr<Sequencer::TrackSequencer>>::operator[](int)

        Zeroing the field that looked like a track index made it worse, because that
        field is a length discriminator -- see dsor/recorded.py. So an animated effect
        is held back until the tail is understood, rather than sent and crashed on.
        """
        return bool(self.start_sequence or self.tick_sequence or self.start_animation)

    def servable(self, known_skills: frozenset[str] = frozenset()) -> bool:
        """Whether every modifier is one this server can serve.

        Permissive by default and strict where it has to be. A modifier that only
        changes a number on the actor, chains another effect or sets a variable is
        fine. One that names a skill is fine when the character has every skill it
        names. One in :data:`FORBIDDEN_ATTRIBUTES` never is, because it reaches into a
        skill's own definition or spawns an actor, and the client asserts rather than
        shrug.

        Being permissive matters: a strict "plain attributes only" rule threw out
        debuff_cc_stun for carrying a StopStatusEffect and debuff_dot_poison for
        chaining an explosion trigger -- the two effects most worth having.
        """
        modifiers = self.starts + self.ticks
        if not modifiers:
            return False
        for modifier in modifiers:
            if modifier.attribute in FORBIDDEN_ATTRIBUTES:
                return False
            named = modifier.skills_named
            if named and not all(skill in known_skills for skill in named):
                return False
        return True


