#!/usr/bin/env python3
"""Generate ``dsor/effects.py`` from the client's own status effect templates.

    python3 tools/effect_table.py ~/dso/db/db_static.sqlite > dsor/effects.py

A skill's effect list names effects; ``_Template_StatusEffect`` says what each one
does. The grammar of both is small and regular:

    UserStatusEffects   skill_warshout_buff_movementspeed,C:1.0,D:10.0,DP:10.0,$0:0.4;
    StartModifiers      Speed:$0,relative,Movement;

So "furious battlecry" -- warshout -- gives 60% of the resource through the skill's own
ResourceGain, then +40% movement speed and +30% damage through two effects. None of it
was served: this server logged "whose effect this server does not model" and stopped.

The table is filtered to the effects the five character classes' skills actually
reference, because the whole thing is 6703 rows.
"""

import re
import pathlib
import sqlite3
import sys

HEADER_COMMENT = (
    "#: What each class skill grants its user, and inflicts on its victim, by\n"
    "#: the skill's wire index. Only the class skills: the strings are long."
)

FIELDS = [
    "Id", "StatusEffectDuration", "StatusEffectTickRate", "MaxStackSize",
    "StartModifiers", "TickModifiers", "StopModifiers", "DoneModifiers",
    "ExclusiveGroup", "Groups", "StartSequence", "TickSequence", "StartAnimation",
    # The aura columns, without which a location effect is an empty container. Every
    # aura this project needed carries no modifiers of its own: skill_earthquake_aura
    # has none, and what it does lives in AuraEffectId -- a *semicolon-separated
    # list* of the effects it puts on whatever stands inside it. Reading the aura and
    # stopping there is why earthquake and defiance looked like effects that did
    # nothing: the crater's stun is skill_earthquake_shockwave_aura's AuraEffectId,
    # and Dragon Hide's free skills are skill_defiance_buff_creators_aura's.
    "AuraEffectId", "AuraRadius", "AuraTargets",
]



def connect(path: str):
    """Open the client's database read-only, and refuse a path that is not one.

    ``sqlite3.connect`` *creates* a database when the file is missing, so running one
    of these from the wrong directory left an empty ``db_static.sqlite`` behind and
    then generated a table with nothing in it. A generator that quietly produces an
    empty module is the same failure as a config file that quietly ignores a key.
    """
    found = pathlib.Path(path)
    if not found.exists():
        raise SystemExit(
            f"no database at {found}. Point this at the client's own, usually "
            "~/dso/db/db_static.sqlite"
        )
    return sqlite3.connect(f"file:{found}?mode=ro", uri=True)


def referenced(db) -> set[str]:
    """Every effect named by any class skill's three effect lists."""
    names: set[str] = set()
    rows = db.execute(
        "SELECT VictimStatusEffects, UserStatusEffects, LocationStatusEffects"
        " FROM _Template_Skill WHERE CharClass <> ''"
    )
    for row in rows:
        for cell in row:
            for entry in (cell or "").split(";"):
                head = entry.split(",")[0].strip()
                if head:
                    names.add(head)

    # And whatever those reach through their auras, transitively. An aura carries no
    # modifiers of its own -- its work is the effects named in AuraEffectId -- and
    # those leaves are named by no skill, so stopping at the skills' own lists left
    # skill_earthquake_dmg, skill_earthquake_shockwave_dmg and Dragon Hide's two
    # resource effects out of the table entirely. Every one of them is the whole of
    # what its skill actually does.
    chain = dict(
        (row[0], row[1] or "")
        for row in db.execute("SELECT Id, AuraEffectId FROM _Template_StatusEffect")
    )
    frontier = set(names)
    while frontier:
        reached = set()
        for name in frontier:
            for leaf in chain.get(name, "").split(";"):
                leaf = leaf.strip()
                if leaf and leaf not in names:
                    reached.add(leaf)
        names |= reached
        frontier = reached
    return names


