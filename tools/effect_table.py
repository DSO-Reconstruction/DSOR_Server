FIELDS = [
    "Id", "StatusEffectDuration", "StatusEffectTickRate", "MaxStackSize",
    "StartModifiers", "TickModifiers", "StopModifiers", "DoneModifiers",
    "ExclusiveGroup", "Groups",
]


def referenced(db) -> set[str]:
    """Every effect named by any class skill's three effect lists."""
    names: set[str] = set()
    rows = db.execute(
        "SELECT VictimStatusEffects, UserStatusEffects, LocationStatusEffects"
        " FROM _Template_Skill WHERE CharClass <> ''"
    )
    for row in rows:
        for cell in row:
            for entry in (cell or "").split(";"):
                head = entry.split(",")[0].strip()
                if head:
                    names.add(head)
    return names


